MAX_WORDS = 6


def dedupe(rows):
    seen, out = set(), []
    for r in rows:
        key = r[0].strip()
        if key in seen:
            continue
        seen.add(key)
        out.append((key,) + tuple(r[1:]))
    return out


def main():
    review = Workbook()
    review.remove(review.active)
    summary = []

    for slug, name, rows in DECKS:
        rows = dedupe(rows)
        too_long = [r[0] for r in rows if len(r[0].split()) > MAX_WORDS]
        if too_long:
            raise SystemExit(f"{slug}: titles over {MAX_WORDS} words: {too_long}")

        # Import file: one column, no header, nothing else.
        wb = Workbook()
        ws = wb.active
        ws.title = "titles"
        ws.sheet_view.rightToLeft = not slug.startswith("04")
        for r in rows:
            ws.append([r[0]])
        ws.column_dimensions["A"].width = 40
        wb.save(OUT / f"{slug}.xlsx")

        # Review sheet: the same titles with context, header row, frozen.
        rs = review.create_sheet(title=slug[:31])
        rs.sheet_view.rightToLeft = not slug.startswith("04")
        rs.append(["العنوان", "النوع", "المصدر", "وين شفناه"])
        for c in rs[1]:
            c.font = Font(bold=True)
        for r in rows:
            rs.append(list(r))
        rs.freeze_panes = "A2"
        for col, w in zip("ABCD", (38, 10, 12, 50)):
            rs.column_dimensions[col].width = w
        for row in rs.iter_rows(min_row=2):
            for c in row:
                c.alignment = Alignment(wrap_text=True, vertical="top")

        summary.append((slug, name, len(rows)))

    review.save(OUT / "REVIEW-all-decks.xlsx")
    for slug, name, n in summary:
        print(f"{n:4d}  {slug}.xlsx  ({name})")


if __name__ == "__main__":
    main()
